"""Writes InklingLamqDigests.swift (the on-device self-check's expected digests) from lamq_digests.json.

    python gen_digests_swift.py [--layer 0]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "Vendor" / "mlx-swift-lm" / "Libraries" / "MLXVLM" / "Models" / "InklingLamqDigests.swift"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--layer", default="0")
    args = ap.parse_args()
    rec = json.loads((HERE / "lamq_digests.json").read_text())
    repo, _, rev = rec["repo"].partition("@")
    layer = rec["layers"][args.layer]
    used = {v["fmt"] for v in layer["linears"].values()}
    luts = {k: v for k, v in rec["luts"].items()}
    lines = [
        "// GENERATED by ios/tools/lamq/gen_digests_swift.py from lamq_digests.json. Do not edit.",
        "// [agent-console patch D] SHA-256 of float32 decoded weights; lamq_ref.py == LookAtMyQuant's",
        f"// decoders bit for bit on {repo}@{rev[:12]} ({rec['checked_tensors']} tensors).",
        "",
        "public enum InklingLamqDigests {",
        f"    public static let layer{args.layer} = InklingLamqExpectedLayer(",
        f'        repo: "{repo}", revision: "{rev}", layer: {int(args.layer)},',
        "        luts: [",
        *[f'            "{k}": "{v}",' for k, v in sorted(luts.items())],
        "        ],",
        "        linears: [",
        *[f'            "{k}": "{v["sha256"]}",' for k, v in layer["linears"].items()],
        "        ],",
        "        gateUp: [",
        *[f'            "{d}",' for d in layer["experts"]["gu"]],
        "        ],",
        "        down: [",
        *[f'            "{d}",' for d in layer["experts"]["dn"]],
        "        ])",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} (formats {sorted(used)})")


if __name__ == "__main__":
    main()
